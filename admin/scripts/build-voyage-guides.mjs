function voyageLiteral(html) {
  const start = html.indexOf('window.__VOYAGE={');
  if (start < 0) throw new Error('window.__VOYAGE literal not found');
  return start;
}

// Replace (or insert after slug:"...") the guide:{...} member of the __VOYAGE literal.
export function setGuide(html, slug, guide) {
  voyageLiteral(html);
  const json = JSON.stringify(guide);
  const at = html.indexOf('guide:{"url"');
  if (at >= 0) {
    let depth = 0, i = at + 'guide:'.length, inStr = false;
    for (; i < html.length; i++) {
      const c = html[i];
      if (inStr) { if (c === '\\') { i++; continue; } if (c === '"') inStr = false; continue; }
      if (c === '"') inStr = true;
      else if (c === '{' || c === '[') depth++;
      else if (c === '}' || c === ']') { depth--; if (depth === 0) break; }
    }
    return html.slice(0, at) + 'guide:' + json + html.slice(i + 1);
  }
  const anchor = `window.__VOYAGE={slug:"${slug}",`;
  if (!html.includes(anchor)) throw new Error(`slug anchor not found for ${slug}`);
  return html.replace(anchor, anchor + 'guide:' + json + ',');
}

// ---- Ship + Ports tabs and the offline search index, embedded in the companion page itself ----
// The companion shows the pack's ship section and its port days as tabs, and searches the whole pack,
// with no network. That content is written into the companion HTML at build time, inside inert
// <template> elements and one JSON data block, between the markers below. Nothing is fetched and
// parsed as HTML at run time; the page ships what it shows, reviewed in git like any other page.
export const MARK_START = '<!-- pack-content:start (generated by admin/scripts/build-voyage-guides.mjs; do not hand-edit) -->';
export const MARK_END = '<!-- pack-content:end -->';
const SEA = /\bsea day\b|cruising at sea|\bat sea\b|scenic cruising/i;

const decode = (s) => String(s)
  .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
  .replace(/&nbsp;/g, ' ').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
export const plain = (html) => decode(String(html).replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

// Split an HTML fragment at headings of the given levels: [{level,id,label,start,end}]
function headings(html, levels) {
  const re = new RegExp(`<h(${levels.join('|')}) id="([^"]+)"[^>]*>([\\s\\S]*?)<\\/h\\1>`, 'g');
  const out = []; let m;
  while ((m = re.exec(html))) out.push({ level: +m[1], id: m[2], label: plain(m[3]), start: m.index });
  out.forEach((h, i) => { h.end = i + 1 < out.length ? out[i + 1].start : html.length; });
  return out;
}

// Rewrite a slice of the guide so it can live inside the companion: ids prefixed (no clash with the
// app's own ids), in-page links pointed at the full guide, images lazy.
function embeddable(slice, guideUrl) {
  return slice
    .replace(/ id="([^"]+)"/g, ' id="pk-$1"')
    .replace(/href="#([^"]+)"/g, (_, a) => `href="${guideUrl}#${a}"`)
    .replace(/<img /g, '<img loading="lazy" decoding="async" ');
}

export function packContent(fragment, guideUrl) {
  const h2 = headings(fragment, [2]);
  const ship = h2.find((h) => /your ship/i.test(h.label));
  const days = h2.find((h) => /day[- ]by[- ]day|leg by leg|the voyage/i.test(h.label));
  const shipHtml = ship ? embeddable(fragment.slice(ship.start, ship.end), guideUrl) : '';
  const portIds = new Set();
  let portsHtml = '';
  if (days) {
    const inner = fragment.slice(days.start, days.end);
    for (const d of headings(inner, [3])) {
      if (SEA.test(d.label)) continue;
      portIds.add(d.id);
      portsHtml += embeddable(inner.slice(d.start, d.end), guideUrl);
    }
  }
  // Search blocks: every h2/h3 slice of the whole pack. Blocks shown in a tab point at the tab's copy.
  const index = [];
  const all = headings(fragment, [2, 3]);
  for (const b of all) {
    const text = plain(fragment.slice(b.start, b.end)).slice(b.label.length).trim();
    let tab = 'guide', anchor = b.id;
    const inShip = ship && b.start >= ship.start && b.start < ship.end;
    if (inShip) { tab = 'ship'; anchor = 'pk-' + b.id; }
    else if (portIds.has(b.id)) { tab = 'ports'; anchor = 'pk-' + b.id; }
    if (/^table of contents$/i.test(b.label)) continue;
    index.push({ t: b.label, s: tab, a: anchor, x: text });
  }
  return { shipHtml, portsHtml, index };
}

export function contentBlock({ shipHtml, portsHtml, index }) {
  const json = JSON.stringify(index).replace(/</g, '\\u003c');
  return MARK_START + '\n'
    + (shipHtml ? '<template id="tpl-ship">\n' + shipHtml + '</template>\n' : '')
    + (portsHtml ? '<template id="tpl-ports">\n' + portsHtml + '</template>\n' : '')
    + '<script type="application/json" id="pack-index">' + json + '</script>\n'
    + MARK_END + '\n';
}

export function setContent(html, block) {
  const a = html.indexOf(MARK_START), b = html.indexOf(MARK_END);
  if (a >= 0 && b > a) return html.slice(0, a) + block + html.slice(b + MARK_END.length + 1);
  const anchor = "<script>if('serviceWorker' in navigator)";
  if (html.split(anchor).length !== 2) throw new Error('service-worker registration line not found once');
  return html.replace(anchor, block + anchor);
}

export function build(p, root = '.') {
  const md = path.join(root, 'admin/voyage-packs', p.slug + '.md');
  const src = readFileSync(md, 'utf8');
  // Pandoc sizes wide tables with <colgroup><col style="width:…">; the guide's CSP allows no inline
  // style, so drop the colgroups rather than leave refused styles in the console. Layout stays automatic.
  const fragment = execFileSync('pandoc', ['-f', 'markdown', '-t', 'html5', '--wrap=none'], { input: src, encoding: 'utf8', maxBuffer: 64 << 20 })
    .replace(/<colgroup>[\s\S]*?<\/colgroup>\n?/g, '');
  const h1 = fragment.match(/<h1[^>]*>([\s\S]*?)<\/h1>/);
  const base = path.basename(p.pwa, '.html');
  const companionHtml = readFileSync(path.join(root, p.pwa), 'utf8');
  const ship = (companionHtml.match(/ship:"([^"]+)"/) || [])[1] || 'voyage';
  const title = h1 ? strip(h1[1]) : p.title;
  const out = page({ title, companionUrl: '/' + p.pwa, companionName: ship, fragment });
  const hash = createHash('sha256').update(TEMPLATE_VERSION + '\n' + out).digest('hex').slice(0, 10);
  const file = path.join(GUIDE_DIR, base + '-guide.html');
  const guide = { url: '/' + file + '?v=' + hash, sections: sectionsOf(fragment) };
  const content = packContent(fragment, guide.url);
  const companion = setContent(setGuide(companionHtml, p.slug, guide), contentBlock(content));
  return { file, out, guide, content, companion, companionPath: p.pwa };
}

const invokedDirectly = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop());
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const only = process.argv.slice(2).find((a) => !a.startsWith('--'));
  let packs;
  try {
    execFileSync('pandoc', ['--version'], { stdio: 'ignore' });
    packs = JSON.parse(readFileSync('admin/voyage-packs/packs.json', 'utf8'));
  } catch (e) {
    console.log(`[guides] UNAVAILABLE: ${e.message}`);
    process.exit(2);
  }
  let stale = 0, built = 0;
  for (const p of packs) {
    if (!p.pwa || (only && p.slug !== only)) continue;
    if (!existsSync(path.join('admin/voyage-packs', p.slug + '.md'))) continue;
    const r = build(p);
    const guideNow = existsSync(r.file) ? readFileSync(r.file, 'utf8') : null;
    const compNow = readFileSync(r.companionPath, 'utf8');
    const isStale = guideNow !== r.out || compNow !== r.companion;
    if (check) { if (isStale) { stale++; console.log(`STALE ${p.slug}`); } continue; }
    mkdirSync(GUIDE_DIR, { recursive: true });
    writeFileSync(r.file, r.out);
    writeFileSync(r.companionPath, r.companion);
    built++;
    console.log(`built ${r.file}  (${r.guide.sections.length} sections; ship ${r.content.shipHtml ? 'yes' : 'NO'}; ports ${(r.content.portsHtml.match(/<h3 /g) || []).length}; search blocks ${r.content.index.length})`);
  }
  if (check) { console.log(stale ? `[guides] REPORT: ${stale} stale` : '[guides] CLEAN'); process.exit(stale ? 3 : 0); }
  console.log(`[guides] built ${built}`);
}
