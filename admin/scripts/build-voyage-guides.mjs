#!/usr/bin/env node
// admin/scripts/build-voyage-guides.mjs — Soli Deo Gloria.
//
// The custom-pack page promises "a PDF to print and an offline-capable HTML version". The offline
// companions carried the itinerary and weather but not the pack itself. This builds, for every
// registry pack that has a companion, a readable HTML guide from the SAME markdown the PDF is built
// from, so the two cannot drift, and records it on the companion as window.__VOYAGE.guide.
//
//   admin/voyage-pwa/guides/<companion>-guide.html   one static page per pack; no script
//   window.__VOYAGE.guide = {url, sections:[{id,label}]}   the companion's Guide tab reads this
//
// The guide URL carries ?v=<hash of the markdown + template>, so an edited pack gets a new URL and a
// phone never keeps reading an old copy out of its offline cache.
//
// Run:  node admin/scripts/build-voyage-guides.mjs            build every guide
//       node admin/scripts/build-voyage-guides.mjs --check    exit 3 if any guide or companion is stale
//       node admin/scripts/build-voyage-guides.mjs <slug>     build one pack
// Three states, never two: CLEAN (0) · REPORT (3, stale) · UNAVAILABLE (2, could not look).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import path from 'node:path';

const TEMPLATE_VERSION = '1';
const GUIDE_DIR = 'admin/voyage-pwa/guides';
const GUIDE_CSS = '/admin/voyage-pwa/guide.css?v=1';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const strip = (s) => String(s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").trim();

export function sectionsOf(html) {
  const out = [];
  const re = /<h2 id="([^"]+)"[^>]*>([\s\S]*?)<\/h2>/g;
  let m;
  while ((m = re.exec(html))) {
    const label = strip(m[2]);
    if (/^table of contents$/i.test(label)) continue;
    out.push({ id: m[1], label });
  }
  return out;
}

export function page({ title, companionUrl, companionName, fragment }) {
  return `<!doctype html>
<!--
  Soli Deo Gloria. Colossians 3:23 "And whatsoever ye do, do it heartily, as to the Lord."
  In the Wake Voyage Pack, offline reading copy. Generated by admin/scripts/build-voyage-guides.mjs
  from the same markdown as the PDF. Do not hand-edit: edit the pack .md and rebuild.
-->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'none'; style-src 'self'; img-src 'self' data: https:; base-uri 'self'; form-action 'none'">
<meta name="referrer" content="strict-origin-when-cross-origin">
<meta name="robots" content="noindex">
<meta name="color-scheme" content="dark">
<meta name="theme-color" content="#03060c">
<title>${esc(title)} · Voyage Pack</title>
<link rel="stylesheet" href="${GUIDE_CSS}">
</head>
<body>
<a class="skip-link" href="#content">Skip to main content</a>
<header class="g-bar" role="banner">
  <a class="g-back" href="${esc(companionUrl)}">← Back to the ${esc(companionName)} companion</a>
</header>
<main id="content" class="g-main">
${fragment}
</main>
<footer class="g-foot" role="contentinfo">
  <p>This is the full Voyage Pack, the same text as the PDF, saved for reading offline.</p>
  <p><a class="g-back" href="${esc(companionUrl)}">← Back to the companion</a></p>
  <p class="g-sdg">Soli Deo Gloria</p>
</footer>
</body>
</html>
`;
}

function voyageLiteral(html) {
  const start = html.indexOf('window.__VOYAGE={');
  if (start < 0) throw new Error('window.__VOYAGE literal not found');
  return start;
}

// Replace (or insert after slug:"...") the guide:{...} member of the __VOYAGE literal.
export function setGuide(html, slug, guide) {
  voyageLiteral(html);
  const json = JSON.stringify(guide);
  const at = html.indexOf('guide:{"url"');
  if (at >= 0) {
    let depth = 0, i = at + 'guide:'.length, inStr = false;
    for (; i < html.length; i++) {
      const c = html[i];
      if (inStr) { if (c === '\\') { i++; continue; } if (c === '"') inStr = false; continue; }
      if (c === '"') inStr = true;
      else if (c === '{' || c === '[') depth++;
      else if (c === '}' || c === ']') { depth--; if (depth === 0) break; }
    }
    return html.slice(0, at) + 'guide:' + json + html.slice(i + 1);
  }
  const anchor = `window.__VOYAGE={slug:"${slug}",`;
  if (!html.includes(anchor)) throw new Error(`slug anchor not found for ${slug}`);
  return html.replace(anchor, anchor + 'guide:' + json + ',');
}

export function build(p, root = '.') {
  const md = path.join(root, 'admin/voyage-packs', p.slug + '.md');
  const src = readFileSync(md, 'utf8');
  // Pandoc sizes wide tables with <colgroup><col style="width:…">; the guide's CSP allows no inline
  // style, so drop the colgroups rather than leave refused styles in the console. Layout stays automatic.
  const fragment = execFileSync('pandoc', ['-f', 'markdown', '-t', 'html5', '--wrap=none'], { input: src, encoding: 'utf8', maxBuffer: 64 << 20 })
    .replace(/<colgroup>[\s\S]*?<\/colgroup>\n?/g, '');
  const h1 = fragment.match(/<h1[^>]*>([\s\S]*?)<\/h1>/);
  const base = path.basename(p.pwa, '.html');
  const companionHtml = readFileSync(path.join(root, p.pwa), 'utf8');
  const ship = (companionHtml.match(/ship:"([^"]+)"/) || [])[1] || 'voyage';
  const title = h1 ? strip(h1[1]) : p.title;
  const out = page({ title, companionUrl: '/' + p.pwa, companionName: ship, fragment });
  const hash = createHash('sha256').update(TEMPLATE_VERSION + '\n' + out).digest('hex').slice(0, 10);
  const file = path.join(GUIDE_DIR, base + '-guide.html');
  const guide = { url: '/' + file + '?v=' + hash, sections: sectionsOf(fragment) };
  return { file, out, guide, companion: setGuide(companionHtml, p.slug, guide), companionPath: p.pwa };
}

const invokedDirectly = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop());
if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const only = process.argv.slice(2).find((a) => !a.startsWith('--'));
  let packs;
  try {
    execFileSync('pandoc', ['--version'], { stdio: 'ignore' });
    packs = JSON.parse(readFileSync('admin/voyage-packs/packs.json', 'utf8'));
  } catch (e) {
    console.log(`[guides] UNAVAILABLE: ${e.message}`);
    process.exit(2);
  }
  let stale = 0, built = 0;
  for (const p of packs) {
    if (!p.pwa || (only && p.slug !== only)) continue;
    if (!existsSync(path.join('admin/voyage-packs', p.slug + '.md'))) continue;
    const r = build(p);
    const guideNow = existsSync(r.file) ? readFileSync(r.file, 'utf8') : null;
    const compNow = readFileSync(r.companionPath, 'utf8');
    const isStale = guideNow !== r.out || compNow !== r.companion;
    if (check) { if (isStale) { stale++; console.log(`STALE ${p.slug}`); } continue; }
    mkdirSync(GUIDE_DIR, { recursive: true });
    writeFileSync(r.file, r.out);
    writeFileSync(r.companionPath, r.companion);
    built++;
    console.log(`built ${r.file}  (${r.guide.sections.length} sections)`);
  }
  if (check) { console.log(stale ? `[guides] REPORT: ${stale} stale` : '[guides] CLEAN'); process.exit(stale ? 3 : 0); }
  console.log(`[guides] built ${built}`);
}
